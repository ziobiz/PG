function escJs(s) {
  return String(s)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r?\n/g, '\\n');
}

const PAIRS_SAFE = PAIRS.filter(function (row) {
  var k = row[0];
  if (!k || typeof k !== 'string') return false;
  if (/[\u3131-\u318E\uAC00-\uD7A3]/.test(k)) return k.length >= 2;
  return k.length >= 2;
});
const PAIRS_SORTED = PAIRS_SAFE.sort(function (a, b) {
  return (b[0] || '').length - (a[0] || '').length;
});

function translateLine(ko, colIdx) {
  var out = ko;
  for (var pi = 0; pi < PAIRS_SORTED.length; pi++) {
    var row = PAIRS_SORTED[pi];
    var k = row[0];
    var rep = row[colIdx + 1];
    if (!k || rep == null) continue;
    /* 4자 이상: 문장 내 부분일치. 2~3자: 전체만(부분치환 시 '삭제'→'削除' 등이 '삭제됩니다'를 깨뜨림). */
    if (k.length >= 4) {
      if (out.indexOf(k) !== -1) out = out.split(k).join(rep);
    } else if (k.length >= 2 && out === k) {
      out = rep;
    } else if (out === k) {
      out = rep;
    }
  }
  return out;
}

function readLabelLines(relPath) {
  try {
    return fs
      .readFileSync(path.join(root, relPath), 'utf8')
      .split(/\r?\n/)
      .map((x) => x.trim())
      .filter(Boolean);
  } catch (e) {
    return [];
  }
}

/** Keys from site/index.html stamped with data-pg-ui-* (merged into string map). */
function readIndexHtmlStampedKeys(relPath) {
  try {
    const s = fs.readFileSync(path.join(root, relPath), 'utf8');
    const set = new Set();
    const attrs = [
      'data-pg-ui-t',
      'data-pg-ui-title',
      'data-pg-ui-placeholder',
      'data-pg-ui-aria-label',
    ];
    for (const attr of attrs) {
      const re = new RegExp(attr + '="([^"]*)"', 'g');
      let m;
      while ((m = re.exec(s))) {
        const v = m[1];
        if (v && /[\u3131-\u318E\uAC00-\uD7A3]/.test(v)) set.add(v);
      }
    }
    return [...set];
  } catch (e2) {
    return [];
  }
}
/** Exclude code fragments mis-extracted into ko-strings-raw.txt (keeps real UI labels only). */
function keepUiStringKey(line) {
  if (line == null || typeof line !== 'string') return false;
  var s = line.trim();
  if (!s) return false;
  if (s.indexOf('\n') >= 0 || s.indexOf('\r') >= 0) return false;
  if (s.length > 400) return false;
  if (!/[\u3131-\u318E\uAC00-\uD7A3]/.test(s)) return false;
  if (
    /\bfunction\b|\breturn\b|\bvar\b|\blet\b|\bconst\b|\bwhile\b|\bfor\b|\bif\s*\(|\belse\b|\bcatch\b|\btry\b/.test(
      s
    )
  )
    return false;
  if (/; \}\)|\}\);\s*$|^\s*[,;(){}\[\]]|,\s*\/\//.test(s)) return false;
  if (/\/\*|\*\/|\/\/\s*placeholder/.test(s)) return false;
  /* 추출 정규식이 인접 따옴표 사이의 주석/JSDoc까지 잡아 맵을 오염시킨다. 코드 주석 라인은 UI 문자열이 아니므로 제외. */
  if (/^\/\//.test(s)) return false;            // // 한 줄 주석 누수
  if (/^\*\s|^\*$/.test(s)) return false;        // * JSDoc 연속 라인
  if (/@param|@return|@see|@code|@example|@throws|\{@/.test(s)) return false;
  if (/\bdocs\/[^\s]*\.md\b/.test(s)) return false; // 문서 경로 주석
  if (/\s\/\/\s/.test(s)) return false;          // 코드 ... // 주석 형태(따옴표 사이 누수)
  /* HTML 조각 누수 제외: screens.js 템플릿의 태그/속성 사이를 따옴표가 가로질러 캡처된 키.
     실제 마크업 안내문(<strong> 등 포함)은 STATIC에 전체 번역으로 별도 등록되므로 자동맵에서 빼도 안전. */
  if (/<\/?[a-zA-Z][^>]*>/.test(s)) return false; // <tag> 또는 </tag>
  if (/(^|[^가-힣])>|<($|[^가-힣])/.test(s) && /(<|>)/.test(s)) {
    // 시작이 '>' 이거나 닫힘 '<' 조각
    if (/^>|<$|>\s*$|^\s*</.test(s)) return false;
  }
  if (/\b(class|value|type|style|id|href|option|span|button|td|th|tr|div|li|strong)\s*=/.test(s)) return false;
  if (/<\/(option|span|button|td|th|tr|div|li|h\d|strong|p|a)>/.test(s)) return false;
  return true;
}

const merged = new Set([
  ...readLabelLines('tools/screen-labels-ko.txt'),
  ...readLabelLines('tools/ko-strings-raw.txt'),
  ...readIndexHtmlStampedKeys('site/index.html'),
]);
const lines = [...merged].filter(keepUiStringKey).sort((a, b) => a.localeCompare(b, 'ko'));

const parts = [
  '/** Auto-generated — tools/build-ui-string-map.mjs */',
  '(function (g) {',
  "  'use strict';",
  '  var M = {};',
];
for (const ko of lines) {
  const en = translateLine(ko, 0);
  const jp = translateLine(ko, 1);
  const ch = translateLine(ko, 2);
  const th = translateLine(ko, 3);
  parts.push("  M['" + escJs(ko) + "']={EN:'" + escJs(en) + "',JP:'" + escJs(jp) + "',CH:'" + escJs(ch) + "',TH:'" + escJs(th) + "'};");
}
parts.push('  g.PG_UI_STRING_MAP = M;');
parts.push('})(typeof window !== "undefined" ? window : globalThis);');

const outPath = path.join(root, 'site/js/pg-ui-string-map.js');
fs.writeFileSync(outPath, parts.join('\n'), 'utf8');
